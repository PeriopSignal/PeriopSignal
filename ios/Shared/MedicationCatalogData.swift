// One row per drug: "id|Name|aliases|flags|class". A leading "*" on the id marks one of the most prescribed outpatient
// drugs, offered first when a short prefix finds many. Aliases are lowercase, comma-separated: brand names first, then
// abbreviations people write ("hctz", "asa", "apap"); the name always finds the entry. Flags are PatientCatalog.medFlags
// ids, space-separated (empty: the drug raises none). The class is the second line of the type-ahead.
//
// Sources. Classes and brand names: the FDA-approved prescribing information (DailyMed, U.S. National Library of
// Medicine, dailymed.nlm.nih.gov: section 1 Indications, section 12.1 Mechanism of action, and the label's Established
// Pharmacologic Class) and Drugs@FDA for the brand names. Written from those labels as known; not re-fetched in this
// session. The flags and the judgment calls behind them:
//   - anticoagulant: vitamin K antagonists, direct oral anticoagulants, low-molecular-weight and unfractionated heparin
//     and fondaparinux (the flag's own definition, "Warfarin, a DOAC or heparin"; the ASRA anticoagulation guideline
//     covers each). Subcutaneous prophylactic heparin is flagged too: its timing matters for a block.
//   - p2y12: clopidogrel, prasugrel, ticagrelor, ticlopidine. Cilostazol, dipyridamole and vorapaxar are antiplatelets
//     that are not P2Y12 inhibitors and raise no flag (their class says what they are).
//   - aspirin: aspirin and every combination containing it (aspirin/dipyridamole, aspirin/omeprazole, Excedrin,
//     Fiorinal, Percodan). Nonacetylated salicylates (salsalate, bismuth subsalicylate, diflunisal) do not acetylate
//     platelet COX and are not flagged.
//   - insulin: every insulin by type and brand, premixes, the inhaled insulin, a pump, and the insulin/GLP-1 combinations
//     (Xultophy, Soliqua: insulin and glp1).
//   - glp1: every GLP-1 receptor agonist, oral semaglutide (Rybelsus) included, and tirzepatide (Mounjaro, Zepbound), a
//     dual GIP/GLP-1 receptor agonist, which the ASA's 2023 consensus guidance on GLP-1 receptor agonists before
//     elective surgery and the 2024 multisociety guidance treat with them.
//   - sglt2: every SGLT2 inhibitor (bexagliflozin and the SGLT1/2 inhibitor sotagliflozin included) and every
//     combination pill containing one (Glyxambi, Synjardy, Trijardy, Xigduo, Qtern, Invokamet, Segluromet, Steglujan):
//     the 2024 AHA/ACC perioperative guideline (Thompson A, et al. Circulation 2024;150:e351–e442) asks for the hold.
//   - betablocker: systemic beta-blockers, labetalol and carvedilol (alpha and beta), sotalol (a class III
//     antiarrhythmic with beta-blockade), and combinations. Timolol eye drops are not flagged: the flag and its 2024
//     AHA/ACC note are about systemic therapy; the class line says "eye drops".
//   - acei: ACE inhibitors, ARBs and combinations containing one; sacubitril/valsartan (an ARNI, which contains an ARB)
//     and sparsentan (an endothelin and angiotensin II receptor antagonist). Aliskiren, a direct renin inhibitor, is
//     neither and is not flagged. Spironolactone, eplerenone and finerenone (mineralocorticoid receptor antagonists)
//     are not flagged.
//   - statin: every statin and combination containing one (Vytorin, Roszet, Caduet).
//   - steroid ("Chronic steroids"): systemic glucocorticoids by mouth or injection (prednisone, prednisolone,
//     methylprednisolone, dexamethasone, hydrocortisone, cortisone, deflazacort); oral budesonide (Entocort EC, Uceris,
//     Ortikos, Tarpeyo, Eohilia), whose labels warn of hypercorticism and adrenal axis suppression with chronic use;
//     and fludrocortisone, kept as the note reader already reads it (a mineralocorticoid, but usually taken for adrenal
//     insufficiency alongside hydrocortisone, which is the stress-dose question; judgment call). Inhaled, nasal and
//     topical corticosteroids are not flagged (Woodcock 2020, Anaesthesia 2020;75:654–663, asks for a judgment by dose
//     there); "Budesonide" alone reads as the inhaled or nasal form.
//   - opioid ("Chronic opioids or buprenorphine"): every opioid agonist or partial agonist and combination, tramadol and
//     tapentadol, methadone, buprenorphine with or without naloxone, butorphanol, and kratom (the FDA's 2018 statement
//     on kratom: its compounds are opioids). Opioid antagonists are NOT flagged and their class says so: naltrexone
//     (Revia, Vivitrol), naltrexone/bupropion (Contrave), olanzapine/samidorphan (Lybalvi), naloxone, nalmefene and the
//     peripheral antagonists (methylnaltrexone, naloxegol, naldemedine). Loperamide and diphenoxylate are not flagged.
//   - maoi: phenelzine, tranylcypromine, isocarboxazid, selegiline (oral and the Emsam patch), rasagiline, safinamide,
//     linezolid (its label: a reversible, nonselective MAO inhibitor) and methylene blue (a reversible MAO-A inhibitor;
//     FDA Drug Safety Communication, July 2011, on serotonin syndrome with serotonergic psychiatric drugs). Uribel and
//     the other urinary combinations hold a small dose of methylene blue and are not flagged (judgment call; their class
//     says so). Tedizolid is not flagged.
//   - Herbal supplements: classes from Ang-Lee MK, Moss J, Yuan CS. Herbal medicines and perioperative care. JAMA
//     2001;286:208–216 (garlic, ginkgo, ginseng, St John's wort, echinacea, ephedra, kava, valerian). They raise no flag.

